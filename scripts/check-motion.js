const { chromium } = require('playwright');
const AxeBuilder = require('@axe-core/playwright').default;
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const target = process.env.PREVIEW_URL || 'http://127.0.0.1:4173';
const report = {};
(async () => {
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
    const page = await context.newPage();
    const errors = [];
    let phase = 'initial';
    page.on('pageerror', error => errors.push({ phase, stack: error.stack }));
    await page.goto(target, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.ditesmoiIntro?.done && window.ditesmoiMotion?.ready);
    const intro = await page.evaluate(() => ({ first: ditesmoiIntro.first, elapsed: ditesmoiIntro.finishedAt - ditesmoiIntro.started }));
    assert.equal(intro.first, true);
    assert.ok(intro.elapsed < 2000, `Intro exceeded budget: ${intro.elapsed}`);
    await page.waitForTimeout(1400);
    assert.ok(await page.evaluate(() => Boolean(ditesmoiMotion.lenis && ditesmoiMotion.horizontal)));
    assert.ok(await page.locator('#hero-title .motion-line').count() > 1);
    assert.match(await page.locator('#hero-title').getAttribute('aria-label'), /Planner in Provence/);
    assert.equal(await page.locator('#hero-title .motion-line').evaluateAll(lines => lines.every(line => Math.abs(gsap.getProperty(line, 'yPercent')) < .1)), true);
    const scrollTo = async y => {
      await page.evaluate(y => { ditesmoiMotion.lenis ? ditesmoiMotion.lenis.scrollTo(y, { immediate: true, force: true }) : window.scrollTo(0, y); ScrollTrigger.update(); }, y);
      await page.waitForTimeout(1450);
    };
    const yFor = selector => page.locator(selector).evaluate(el => el.getBoundingClientRect().top + scrollY);
    const statsY = await yFor('.stats-band');
    await scrollTo(statsY - 250);
    assert.deepEqual(await page.locator('[data-count]').allTextContents(), ['2005', '2', '4']);
    assert.equal(await page.locator('.enquire-pill').isVisible(), true);
    phase = 'pin';
    const pin = await page.evaluate(() => ({ start: ditesmoiMotion.horizontal.start, end: ditesmoiMotion.horizontal.end }));
    const panels = [];
    for (let i = 0; i < 4; i++) {
      await scrollTo(pin.start + (pin.end - pin.start) * i / 3);
      const result = await page.evaluate(() => ({ index: document.querySelector('#destinations').dataset.destinationIndex, progress: document.querySelector('.destination-current').textContent, overflow: document.documentElement.scrollWidth > innerWidth, tone: [...document.querySelectorAll('.destination-tints > span')].map(el => getComputedStyle(el).opacity), x: gsap.getProperty(document.querySelector('.destination-rows'), 'x') }));
      assert.equal(Number(result.index), i);
      assert.equal(result.progress, String(i + 1).padStart(2, '0'));
      assert.equal(result.overflow, false);
      assert.ok(Number(result.tone[i]) > .95);
      const contrast = await new AxeBuilder({ page }).include('#destinations').withRules(['color-contrast']).analyze();
      assert.deepEqual(contrast.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), [], `Destination ${i + 1} contrast`);
      panels.push(result);
    }
    phase = 'keyboard';
    const fourthLink = page.locator('.destination-row').nth(3).locator('a');
    await fourthLink.focus();
    await page.keyboard.press('Home');
    await page.waitForTimeout(2400);
    assert.equal(await page.locator('.destination-current').innerText(), '01');
    await page.keyboard.press('End');
    await page.waitForTimeout(2400);
    assert.equal(await page.locator('.destination-current').innerText(), '04');
    await page.locator('.site-header .wordmark').focus();
    await scrollTo((await yFor('.gallery-canvas')) - 140);
    phase = 'gallery';
    const frame = page.locator('.gallery-image').first();
    const box = await frame.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.waitForTimeout(900);
    assert.equal(await page.locator('.motion-cursor').evaluate(el => el.classList.contains('is-view')), true);
    assert.ok(Math.abs(await page.locator('.motion-cursor').evaluate(el => gsap.getProperty(el, 'scaleX')) - 1) < .01);
    phase = 'viewer';
    await frame.locator('button').click();
    assert.equal(await page.locator('.image-viewer').evaluate(el => el.open), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.image-viewer').evaluate(el => el.open), false);
    phase = 'closing';
    await scrollTo((await yFor('.closing-cta')) - 120);
    assert.equal(await page.locator('.enquire-pill').isVisible(), false);
    const button = page.locator('.button-filled');
    const buttonBox = await button.boundingBox();
    await page.mouse.move(buttonBox.x + buttonBox.width - 3, buttonBox.y + 4);
    await page.waitForTimeout(900);
    const pull = await button.evaluate(el => ({ x: gsap.getProperty(el, 'x'), y: gsap.getProperty(el, 'y') }));
    assert.ok(Math.hypot(pull.x, pull.y) <= 6.01);
    await page.mouse.move(1, 200);
    await page.waitForTimeout(1100);
    assert.ok(Math.abs(await button.evaluate(el => gsap.getProperty(el, 'x'))) < .1);
    phase = 'axe';
    const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    assert.deepEqual(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), []);
    phase = 'reduce';
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.waitForTimeout(300);
    const reset = await page.evaluate(() => ({ lenis: !!ditesmoiMotion.lenis, pin: !!ditesmoiMotion.horizontal, lines: document.querySelectorAll('.motion-line').length, wipes: document.querySelectorAll('.image-wipe').length, horizontal: document.querySelector('#destinations').classList.contains('motion-horizontal'), cursor: document.querySelector('.motion-cursor').classList.contains('is-enabled') }));
    assert.deepEqual(reset, { lenis: false, pin: false, lines: 0, wipes: 0, horizontal: false, cursor: false });
    phase = 'restore';
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.waitForTimeout(300);
    assert.ok(await page.evaluate(() => Boolean(ditesmoiMotion.lenis && ditesmoiMotion.horizontal)));
    phase = 'reload';
    await page.reload({ waitUntil: 'domcontentloaded' });
    assert.equal(await page.evaluate(() => ditesmoiIntro.first), false);
    assert.deepEqual(errors, []);
    report.desktop = { introMs: Math.round(intro.elapsed), sessionOnly: true, lenis: true, horizontalPanels: panels, keyboardNavigation: true, countUp: true, customCursor: true, lightbox: true, magneticPull: pull, enquireVisibility: true, preferenceToggleCleanup: reset, accessibilityViolations: 0 };
    await context.close();

    const skipContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const skip = await skipContext.newPage();
    await skip.goto(target, { waitUntil: 'commit' });
    await skip.locator('.intro-skip').click({ force: true, timeout: 1500 });
    await skip.waitForFunction(() => ditesmoiIntro.done);
    report.skip = await skip.evaluate(() => ({ endedMs: ditesmoiIntro.finishedAt - ditesmoiIntro.started, visible: document.getElementById('motion-intro').open }));
    assert.equal(report.skip.visible, false);
    await skipContext.close();

    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, reducedMotion: 'no-preference' });
    const mobile = await mobileContext.newPage();
    const mobileErrors = [];
    mobile.on('pageerror', error => mobileErrors.push(error.message));
    await mobile.goto(target);
    await mobile.waitForFunction(() => ditesmoiMotion.ready && ditesmoiIntro.done);
    assert.equal(await mobile.evaluate(() => !!ditesmoiMotion.lenis || !!ditesmoiMotion.horizontal), false);
    assert.equal(await mobile.locator('.motion-cursor').evaluate(el => getComputedStyle(el).display), 'none');
    const y = await mobile.locator('#destinations').evaluate(el => el.getBoundingClientRect().top + scrollY);
    await mobile.evaluate(y => window.scrollTo(0, y), y);
    await mobile.waitForTimeout(1500);
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await mobile.locator('.destination-row').count(), 4);
    const mobileAxe = await new AxeBuilder({ page: mobile }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    assert.deepEqual(mobileAxe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), []);
    assert.deepEqual(mobileErrors, []);
    report.mobile = { nativeScroll: true, verticalDestinations: true, noCustomCursor: true, noOverflow: true, accessibilityViolations: 0 };
    await mobileContext.close();

    const blocked = await browser.newContext({ reducedMotion: 'no-preference' });
    await blocked.addInitScript(() => { Object.defineProperty(window, 'sessionStorage', { get() { throw new DOMException('Blocked', 'SecurityError'); } }); });
    const blockedPage = await blocked.newPage();
    await blockedPage.goto(target);
    await blockedPage.waitForFunction(() => ditesmoiMotion.ready);
    assert.equal(await blockedPage.evaluate(() => ditesmoiIntro.first), false);
    assert.equal(await blockedPage.locator('#hero-title').isVisible(), true);
    report.blockedSessionStorage = 'gracefully skipped intro';
    await blocked.close();
    const fallback = await browser.newContext();
    await fallback.route('**/assets/vendor/*.js', route => route.abort());
    const fallbackPage = await fallback.newPage();
    const fallbackErrors = [];
    fallbackPage.on('pageerror', error => fallbackErrors.push(error.message));
    await fallbackPage.goto(target);
    await fallbackPage.waitForTimeout(2000);
    assert.equal(await fallbackPage.locator('#hero-title').isVisible(), true);
    assert.equal(await fallbackPage.locator('#motion-intro').evaluate(el => el.open), false);
    assert.deepEqual(fallbackErrors, []);
    report.libraryFailure = 'content and native scrolling remain usable';
    await fallback.close();
    await fs.writeFile('preview/motion-results.json', JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
